#!/usr/bin/env bash
# Turn a built .deb into an Arch Linux package with the same files: .PKGINFO + .MTREE + payload,
# laid out the way makepkg writes them, so `pacman -U` installs it and `pacman -Qkk` checks it.
# Usage: build-arch-package.sh <deb> <out.pkg.tar.zst> <pkgname> <x86_64|aarch64> <version> <desc> <depends...>
# Needs dpkg-deb, bsdtar (libarchive-tools), zstd and fakeroot.
set -euo pipefail

deb=$(realpath "$1")
out=$(realpath -m "$2")
pkgname=$3
arch=$4
version=$5
desc=$6
shift 6
depends=("$@")

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
export deb out pkgname arch version desc work
export DEPENDS="${depends[*]}"

# fakeroot so the payload and .MTREE record root ownership, as makepkg's do.
fakeroot -- bash -euo pipefail -c '
  root="$work/pkg"
  mkdir -p "$root"
  dpkg-deb -x "$deb" "$root"
  rm -rf "$root/usr/share/doc"
  chown -R 0:0 "$root"
  cd "$root"
  size=$(du -sb --apparent-size . | cut -f1)
  {
    echo "# Generated by rusty-backup scripts/ci/build-arch-package.sh"
    echo "pkgname = $pkgname"
    echo "pkgbase = $pkgname"
    echo "xdata = pkgtype=pkg"
    echo "pkgver = ${version}-1"
    echo "pkgdesc = $desc"
    echo "url = https://github.com/danifunker/rusty-backup"
    echo "builddate = $(date +%s)"
    echo "packager = Rusty Backup CI <noreply@github.com>"
    echo "size = $size"
    echo "arch = $arch"
    echo "license = AGPL-3.0-only"
    for d in $DEPENDS; do echo "depend = $d"; done
  } > .PKGINFO
  chown 0:0 .PKGINFO
  # The file list makepkg uses: .PKGINFO first, then everything else sorted, without ./ prefixes.
  list() { printf "%s\0" .PKGINFO; find . -mindepth 1 ! -name .PKGINFO ! -name .MTREE -print0 | sort -z | sed -z "s|^\./||"; }
  list | LANG=C bsdtar -cnf - --format=mtree \
    --options="!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link" \
    --null --files-from - --exclude .MTREE | gzip -c -f -n > .MTREE
  chown 0:0 .MTREE
  { printf "%s\0" .MTREE; list; } | LANG=C bsdtar --no-fflags -cnf - --null --files-from - \
    | zstd -q -f -19 -T0 -o "$out"
'
echo "built $out ($(stat -c %s "$out") bytes): $pkgname ${version}-1 $arch, depends: ${depends[*]}"
