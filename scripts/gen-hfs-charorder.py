#!/usr/bin/env python3
"""Generate crates/fs-mac-unicode/src/hfs_charorder.rs, the classic HFS name order.

Usage (macOS only): gen-hfs-charorder.py \
    | rustfmt --edition 2021 --emit stdout > crates/fs-mac-unicode/src/hfs_charorder.rs

Classic HFS compares catalog names with the system's RelString (case-insensitive,
diacritic-sensitive). This builds scripts/hfs-relstring-pairs.c against CoreServices,
asks Apple's RelString about every pair of one-byte names, and turns the answers into a
rank per Mac Roman byte (bytes that compare equal share a rank). Names then compare rank
by rank, the shorter first on a common prefix; that rule was checked against RelString on
300,000 random multi-byte pairs.
"""
import os
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
with tempfile.TemporaryDirectory() as tmp:
    exe = os.path.join(tmp, "pairs")
    subprocess.run(
        ["clang", "-w", "-o", exe, os.path.join(here, "hfs-relstring-pairs.c"), "-framework", "CoreServices"],
        check=True,
    )
    rows = subprocess.run([exe], check=True, capture_output=True, text=True).stdout.split()

assert len(rows) == 256 and all(len(r) == 256 for r in rows)
below = [r.count("2") for r in rows]
classes = sorted(set(below))
rank = [classes.index(b) for b in below]
for i in range(256):
    for j in range(256):
        want = "1" if rank[i] == rank[j] else ("0" if rank[i] < rank[j] else "2")
        assert rows[i][j] == want, "RelString is not a total preorder"

print("// @generated by scripts/gen-hfs-charorder.py from Apple's RelString; do not edit.")
print()
print(f"/// Classic HFS sort rank of each Mac Roman byte ({len(classes)} ranks; equal rank = same name).")
print("pub(crate) static HFS_RANK: [u8; 256] = [")
for i in range(0, 256, 16):
    print("    " + " ".join(f"{r:3}," for r in rank[i : i + 16]) + f" // 0x{i:02X}")
print("];")
