#!/usr/bin/env python3
"""Generate crates/fs-mac-unicode/src/hfsplus_tables.rs, the HFS+ name tables.

Usage: gen-hfsplus-tables.py UnicodeData-3.2.0.txt FastUnicodeCompare.c > hfsplus_tables.rs

Sources (see crates/fs-mac-unicode/README.md):
- Case folding and the ignorable set: the gLowerCaseTable mapping in FastUnicodeCompare.c,
  the download attached to Apple TN1150 (tn1150.1.hqx). Only the resulting mapping is used;
  it is re-encoded here as a sorted list of the code points that do not fold to themselves.
- Decomposition: UnicodeData.txt 3.2.0 canonical mappings, applied recursively and put in
  canonical order, skipping U+2000-U+2FFF and U+F900-U+FAFF as TN1150 says (Mac OS X 10.3
  and later use Unicode 3.2). Hangul is algorithmic and handled in code.
- Canonical combining classes: UnicodeData.txt 3.2.0 field 3.

Checked against real macOS: names created on an HFS+ image by the macOS kernel store
exactly these decompositions for every one of the 1,391 BMP code points that any table
decomposes.
"""
import re
import sys


def load_ucd(path):
    dec, ccc = {}, {}
    for line in open(path, encoding="ascii"):
        f = line.split(";")
        c = int(f[0], 16)
        if c > 0xFFFF:
            continue
        if f[3] != "0":
            ccc[c] = int(f[3])
        if f[5] and not f[5].startswith("<"):
            dec[c] = [int(x, 16) for x in f[5].split()]
    return dec, ccc


def load_fold(path):
    src = open(path, encoding="latin-1").read()
    body = re.search(r"gLowerCaseTable\s*\[\s*\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", body), flags=re.S)
    tab = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", body)]

    def fold(c):
        sub = tab[c >> 8]
        return c if sub == 0 else tab[sub + (c & 0xFF)]

    return [(c, fold(c)) for c in range(0x10000) if fold(c) != c]


def excluded(c):
    return 0x2000 <= c <= 0x2FFF or 0xF900 <= c <= 0xFAFF


def decompositions(dec, ccc):
    def full(c):
        return [c] if c not in dec else [y for x in dec[c] for y in full(x)]

    def canonical(seq):
        s = list(seq)
        for i in range(1, len(s)):
            j = i
            while j > 0 and ccc.get(s[j], 0) and ccc.get(s[j - 1], 0) > ccc[s[j]]:
                s[j - 1], s[j] = s[j], s[j - 1]
                j -= 1
        return s

    return {c: canonical(full(c)) for c in sorted(dec) if not excluded(c)}


def rows(items, per_line, fmt):
    out = []
    for i in range(0, len(items), per_line):
        out.append("    " + " ".join(fmt(x) for x in items[i : i + per_line]))
    return "\n".join(out)


def main():
    dec, ccc = load_ucd(sys.argv[1])
    fold = load_fold(sys.argv[2])
    decomp = decompositions(dec, ccc)
    pool, index = [], []
    for c, seq in decomp.items():
        index.append((c, len(pool), len(seq)))
        pool.extend(seq)
    assert len(pool) < 0x10000 and max(n for _, _, n in index) <= 4
    combining = sorted(ccc.items())

    print("// @generated by scripts/gen-hfsplus-tables.py from Unicode 3.2.0 and Apple TN1150; do not edit.")
    print("// Unicode data: Copyright (c) 1991-2002 Unicode, Inc., under the Unicode licence (see README).")
    print()
    print("/// Code points whose HFS+ fold is not themselves, sorted: (code, fold); fold 0 = ignored.")
    print(f"pub(crate) static FOLD: [(u16, u16); {len(fold)}] = [")
    print(rows(fold, 6, lambda p: f"(0x{p[0]:04X}, 0x{p[1]:04X}),"))
    print("];")
    print()
    print("/// Code points HFS+ stores decomposed, sorted: (code, start in DECOMP_POOL, length).")
    print(f"pub(crate) static DECOMP: [(u16, u16, u8); {len(index)}] = [")
    print(rows(index, 5, lambda t: f"(0x{t[0]:04X}, {t[1]}, {t[2]}),"))
    print("];")
    print()
    print("/// The decomposed sequences, back to back, in canonical order.")
    print(f"pub(crate) static DECOMP_POOL: [u16; {len(pool)}] = [")
    print(rows(pool, 10, lambda u: f"0x{u:04X},"))
    print("];")
    print()
    print("/// Non-zero canonical combining classes, sorted: (code, class).")
    print(f"pub(crate) static COMBINING_CLASS: [(u16, u8); {len(combining)}] = [")
    print(rows(combining, 7, lambda p: f"(0x{p[0]:04X}, {p[1]}),"))
    print("];")


if __name__ == "__main__":
    main()
