//! HFS+ name normalisation: Apple's case folding and the canonical decomposition HFS+
//! stores names in (TN1150, "HFS Plus Names" and "Unicode Subtleties").
//!
//! - [`case_fold`]: the fold `FastUnicodeCompare` applies; 0 marks an ignorable code point
//!   and NUL folds to 0xFFFF.
//! - [`decompose`] / [`decompose_str`]: Unicode 3.2 canonical decomposition, as Mac OS X 10.3
//!   and later write it, except U+2000-U+2FFF and U+F900-U+FAFF; Hangul syllables become
//!   conjoining jamo. [`decompose_str`] also puts combining marks in canonical order.
//!
//! The tables live in `hfsplus_tables.rs`, generated by `scripts/gen-hfsplus-tables.py`
//! (see this crate's README for the sources and how they were checked against macOS).

use crate::hfsplus_tables::{COMBINING_CLASS, DECOMP, DECOMP_POOL, FOLD};

const HANGUL_FIRST: u16 = 0xAC00;
const HANGUL_LAST: u16 = 0xD7A3;
const JAMO_L: u16 = 0x1100;
const JAMO_V: u16 = 0x1161;
const JAMO_T: u16 = 0x11A7;
const V_COUNT: u16 = 21;
const T_COUNT: u16 = 28;

/// The HFS+ case-insensitive fold of `c`: 0 when HFS+ ignores it in comparisons.
pub fn case_fold(c: u16) -> u16 {
    if c < 0x80 {
        // ASCII, the common case: only NUL and A-Z are in the table.
        return match c {
            0 => 0xFFFF,
            0x41..=0x5A => c + 0x20,
            _ => c,
        };
    }
    match FOLD.binary_search_by_key(&c, |&(code, _)| code) {
        Ok(i) => FOLD[i].1,
        Err(_) => c,
    }
}

/// The units HFS+ stores for `uc`: its canonical decomposition, or `uc` itself.
pub fn decompose(uc: u16, buf: &mut [u16; 3]) -> &[u16] {
    if (HANGUL_FIRST..=HANGUL_LAST).contains(&uc) {
        let s = uc - HANGUL_FIRST;
        buf[0] = JAMO_L + s / (V_COUNT * T_COUNT);
        buf[1] = JAMO_V + (s % (V_COUNT * T_COUNT)) / T_COUNT;
        let t = s % T_COUNT;
        if t == 0 {
            return &buf[..2];
        }
        buf[2] = JAMO_T + t;
        return &buf[..3];
    }
    let found = if uc < DECOMP[0].0 {
        Err(0) // nothing below U+00C0 decomposes
    } else {
        DECOMP.binary_search_by_key(&uc, |&(code, _, _)| code)
    };
    match found {
        Ok(i) => {
            let (_, start, len) = DECOMP[i];
            &DECOMP_POOL[start as usize..start as usize + len as usize]
        }
        Err(_) => {
            buf[0] = uc;
            &buf[..1]
        }
    }
}

/// A name as HFS+ stores it: UTF-16, fully decomposed, combining marks in canonical order.
pub fn decompose_str(name: &str) -> Vec<u16> {
    let mut out = Vec::with_capacity(name.len());
    let mut buf = [0u16; 3];
    for unit in name.encode_utf16() {
        out.extend_from_slice(decompose(unit, &mut buf));
    }
    canonical_order(&mut out);
    out
}

/// The canonical combining class of `c` (0 for starters and anything unlisted).
fn combining_class(c: u16) -> u8 {
    match COMBINING_CLASS.binary_search_by_key(&c, |&(code, _)| code) {
        Ok(i) => COMBINING_CLASS[i].1,
        Err(_) => 0,
    }
}

/// Stable-sort each run of combining marks by class; starters (class 0) never move.
fn canonical_order(s: &mut [u16]) {
    for i in 1..s.len() {
        let class = combining_class(s[i]);
        if class == 0 {
            continue;
        }
        let mut j = i;
        while j > 0 && combining_class(s[j - 1]) > class {
            s.swap(j - 1, j);
            j -= 1;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(s: &[u16]) -> Vec<String> {
        s.iter().map(|u| format!("{u:04X}")).collect()
    }

    fn dec(c: u16) -> Vec<String> {
        hex(decompose(c, &mut [0; 3]))
    }

    #[test]
    fn ascii_fast_paths_agree_with_the_tables() {
        for c in 0..0x80u16 {
            let table = FOLD
                .binary_search_by_key(&c, |&(code, _)| code)
                .map_or(c, |i| FOLD[i].1);
            assert_eq!(case_fold(c), table, "U+{c:04X}");
        }
        assert_eq!(DECOMP[0].0, 0x00C0);
    }

    #[test]
    fn tables_are_sorted_for_binary_search() {
        assert!(FOLD.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(DECOMP.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(COMBINING_CLASS.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn folding_is_to_lowercase_with_nul_last_and_ignorables_dropped() {
        assert_eq!(case_fold(b'A' as u16), b'a' as u16);
        assert_eq!(case_fold(b'a' as u16), b'a' as u16);
        assert_eq!(case_fold(b'_' as u16), b'_' as u16);
        assert_eq!(case_fold(0x0000), 0xFFFF);
        assert_eq!(case_fold(0x00C6), 0x00E6);
        assert_eq!(
            case_fold(0x00C9),
            0x00C9,
            "precomposed: never stored, so not folded"
        );
        assert_eq!(case_fold(0x0391), 0x03B1);
        assert_eq!(case_fold(0x0410), 0x0430);
        assert_eq!(case_fold(0x200C), 0, "zero-width non-joiner is ignored");
        assert_eq!(case_fold(0xFEFF), 0, "BOM / ZWNBSP is ignored");
        assert_eq!(case_fold(0x00DF), 0x00DF, "sharp s folds to itself");
        assert_eq!(case_fold(0xFF21), 0xFF41, "fullwidth A");
    }

    /// Each pair is what macOS wrote into an HFS+ catalog for a name holding the character.
    #[test]
    fn decompositions_match_what_macos_stores() {
        for (c, want) in [
            (0x00C0, &["0041", "0300"][..]),
            (0x01F8, &["004E", "0300"]),
            (0x0218, &["0053", "0326"]),
            (0x022A, &["004F", "0308", "0304"]),
            (0x0310, &["0310"]),
            (0x0344, &["0308", "0301"]),
            (0x0386, &["0391", "0301"]),
            (0x0390, &["03B9", "0308", "0301"]),
            (0x0400, &["0415", "0300"]),
            (0x04D4, &["04D4"]),
            (0x04DA, &["04D8", "0308"]),
            (0x04EC, &["042D", "0308"]),
            (0x09B0, &["09B0"]),
            (0x0E33, &["0E33"]),
            (0x0F77, &["0F77"]),
            (0x1E9B, &["017F", "0307"]),
            (0x1F82, &["03B1", "0313", "0300", "0345"]),
            (0x2126, &["2126"]),
            (0xF900, &["F900"]),
        ] {
            assert_eq!(dec(c), want, "U+{c:04X}");
        }
    }

    #[test]
    fn hangul_syllables_become_conjoining_jamo() {
        assert_eq!(dec(0xAC00), ["1100", "1161"]);
        assert_eq!(dec(0xAC01), ["1100", "1161", "11A8"]);
        assert_eq!(dec(0xD7A3), ["1112", "1175", "11C2"]);
    }

    #[test]
    fn names_are_put_in_canonical_order_across_characters() {
        // macOS stores all three as base + dot below (220) + acute (230).
        assert_eq!(
            hex(&decompose_str("a\u{301}\u{323}")),
            ["0061", "0323", "0301"]
        );
        assert_eq!(
            hex(&decompose_str("\u{E1}\u{323}")),
            ["0061", "0323", "0301"]
        );
        assert_eq!(
            hex(&decompose_str("\u{1E05}\u{301}")),
            ["0062", "0323", "0301"]
        );
        assert_eq!(hex(&decompose_str("\u{300}\u{316}")), ["0316", "0300"]);
        assert_eq!(
            hex(&decompose_str("Caf\u{E9}")),
            ["0043", "0061", "0066", "0065", "0301"]
        );
    }

    #[test]
    fn characters_outside_the_bmp_pass_through_as_surrogates() {
        assert_eq!(hex(&decompose_str("\u{1F600}")), ["D83D", "DE00"]);
    }
}
